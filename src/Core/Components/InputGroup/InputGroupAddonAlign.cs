namespace Vela.UI.Components;

/// <summary>
/// Where an <see cref="InputGroupAddon"/> sits around the control.
/// </summary>
public enum InputGroupAddonAlign
{
    /// <summary>
    /// Before the control, on the same line.
    /// </summary>
    InlineStart,

    /// <summary>
    /// After the control, on the same line.
    /// </summary>
    InlineEnd,

    /// <summary>
    /// Above the control, across the full width.
    /// </summary>
    BlockStart,

    /// <summary>
    /// Below the control, across the full width.
    /// </summary>
    BlockEnd,
}
