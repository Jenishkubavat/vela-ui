namespace Vela.UI.Components;

/// <summary>
/// The padding and spacing of an <see cref="Item"/>.
/// </summary>
public enum ItemSize
{
    /// <summary>
    /// The standard padding.
    /// </summary>
    Default,

    /// <summary>
    /// The same padding, with smaller media and tighter spacing in an <see cref="ItemGroup"/>.
    /// </summary>
    Small,

    /// <summary>
    /// Compact, for dense lists and menus.
    /// </summary>
    ExtraSmall,
}
