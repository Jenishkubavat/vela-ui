namespace Vela.UI.Components;

/// <summary>
/// The height of a <see cref="Toggle"/>, matching the <see cref="Button"/> sizes.
/// </summary>
public enum ToggleSize
{
    /// <summary>
    /// 32px. The default.
    /// </summary>
    Default,

    /// <summary>
    /// 28px, for dense toolbars.
    /// </summary>
    Small,

    /// <summary>
    /// 40px.
    /// </summary>
    Large,
}
