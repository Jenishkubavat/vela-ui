namespace Vela.UI.Components;

/// <summary>
/// The visual style of a <see cref="Toggle"/>.
/// </summary>
public enum ToggleVariant
{
    /// <summary>
    /// No edge until pressed. The default, for toolbars.
    /// </summary>
    Default,

    /// <summary>
    /// A hairline edge in both states, for a toggle standing on its own.
    /// </summary>
    Outline,
}
